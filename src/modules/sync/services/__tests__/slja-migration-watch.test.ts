import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
const mocks = vi.hoisted(() => ({ session: vi.fn(), candidates: vi.fn(), confirm: vi.fn(), migrate: vi.fn() }))
vi.mock('@modules/media/services/auth-client', () => ({ getAuthSession: mocks.session }))
vi.mock('@shared/composables/useAppConfirm', () => ({ appConfirm: mocks.confirm }))
vi.mock('@plugins/i18n', () => ({ default: { global: { t: (key: string) => key } } }))
vi.mock('../local-slja-migration', () => ({ localSljaMigrationCandidates: mocks.candidates, runSljaMigration: mocks.migrate }))
let beforeUnload: (() => void) | undefined
beforeEach(() => {
  vi.resetModules(); vi.resetAllMocks(); vi.useFakeTimers()
  mocks.session.mockReturnValue({ token:'session-1' })
  mocks.candidates.mockReturnValue([{ id:'slja-1' }])
  mocks.confirm.mockResolvedValue(true)
  mocks.migrate.mockResolvedValue(undefined)
  vi.spyOn(window, 'addEventListener').mockImplementation((_type, callback) => { beforeUnload = callback as () => void })
})
afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks() })
describe('oferta de migração após login', () => {
  it.each([true, false])('pergunta uma vez por sessão e transmite decisão %s', async approved => {
    mocks.confirm.mockResolvedValue(approved)
    const { startSljaMigrationWatch } = await import('../slja-migration-watch')
    startSljaMigrationWatch(); startSljaMigrationWatch()
    await vi.advanceTimersByTimeAsync(45000)
    expect(mocks.confirm).toHaveBeenCalledOnce()
    const options = mocks.migrate.mock.calls[0]![1]
    expect(await options.confirmUpload()).toBe(approved)
    expect(mocks.migrate.mock.calls[0]![0]).toEqual([{ id:'slja-1' }])
    beforeUnload!()
    const count = mocks.session.mock.calls.length
    await vi.advanceTimersByTimeAsync(30000)
    expect(mocks.session).toHaveBeenCalledTimes(count)
  })
  it('não pergunta sem sessão ou sem arquivos locais, e volta a oferecer depois de novo login', async () => {
    mocks.session.mockReturnValue(null)
    const { startSljaMigrationWatch } = await import('../slja-migration-watch')
    startSljaMigrationWatch()
    await vi.advanceTimersByTimeAsync(15000)
    expect(mocks.candidates).not.toHaveBeenCalled()
    mocks.session.mockReturnValue({ token:'session-1' })
    mocks.candidates.mockReturnValue([])
    await vi.advanceTimersByTimeAsync(15000)
    expect(mocks.confirm).not.toHaveBeenCalled()
    mocks.session.mockReturnValue(null)
    await vi.advanceTimersByTimeAsync(15000)
    mocks.session.mockReturnValue({ token:'session-1' })
    mocks.candidates.mockReturnValue([{ id:'new' }])
    await vi.advanceTimersByTimeAsync(15000)
    expect(mocks.confirm).toHaveBeenCalledOnce()
  })
  it('uma confirmação rejeitada equivale a recusa e falha da migração não encerra o observador', async () => {
    mocks.confirm.mockRejectedValue(new Error('dialog closed'))
    mocks.migrate.mockRejectedValue(new Error('offline'))
    const { startSljaMigrationWatch } = await import('../slja-migration-watch')
    startSljaMigrationWatch()
    await vi.advanceTimersByTimeAsync(15000)
    expect(await mocks.migrate.mock.calls[0]![1].confirmUpload()).toBe(false)
    mocks.session.mockReturnValue({ token:'session-2' })
    await vi.advanceTimersByTimeAsync(15000)
    expect(mocks.migrate).toHaveBeenCalledTimes(2)
  })
})
