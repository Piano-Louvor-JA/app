  function detect() {
    try { var s = localStorage.getItem('palcoLang'); if (s && LOCALES[s]) return s; } catch (e) {}
    try {
      var q = new URLSearchParams(location.search).get('lang');
      if (q) { q = String(q).replace('_', '-').toLowerCase(); if (LOCALES[q]) return q;
        var p2 = q.split('-')[0]; var hit = Object.keys(LOCALES).filter(function (k) { return k.split('-')[0] === p2; })[0];
        if (hit) return hit; }
    } catch (e) {}
    var nav = (navigator.language || navigator.userLanguage || 'en').replace('_', '-').toLowerCase();
    if (LOCALES[nav]) return nav;
    var pre = nav.split('-')[0];
    var hit2 = Object.keys(LOCALES).filter(function (k) { return k.split('-')[0] === pre; })[0];
    return hit2 || 'en';
  }

  var lang = detect();
  var dict = LOCALES[lang] || LOCALES.en;

  function t(key) { return dict[key] || (LOCALES.en[key] != null ? LOCALES.en[key] : key); }
  function fmt(key, vars) {
    var s = t(key);
    if (vars) Object.keys(vars).forEach(function (k) { s = s.split('{' + k + '}').join(String(vars[k])); });
    return s;
  }
  function esc(s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); }

  function init() {
    var d = document.documentElement;
    d.setAttribute('lang', lang);
    if (lang === 'ar') d.setAttribute('dir', 'rtl');
    var n = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < n.length; i++) n[i].textContent = t(n[i].getAttribute('data-i18n'));
    n = document.querySelectorAll('[data-i18n-title]');
    for (var j = 0; j < n.length; j++) n[j].setAttribute('title', t(n[j].getAttribute('data-i18n-title')));
    n = document.querySelectorAll('[data-i18n-placeholder]');
    for (var k = 0; k < n.length; k++) n[k].setAttribute('placeholder', t(n[k].getAttribute('data-i18n-placeholder')));
    var tt = document.querySelector('title[data-i18n]');
    if (tt) tt.textContent = t(tt.getAttribute('data-i18n'));
  }

  window.PALCO_I18N = { t: t, fmt: fmt, esc: esc, init: init, lang: lang, locales: LOCALES };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
